const AUDIT_ENTITY = 'Movie';

/** Transactions tried per create when an auto-generated slug keeps clashing with a concurrent insert. */
export const AUTO_SLUG_MAX_ATTEMPTS = 3;

export const SLUG_IN_USE_MESSAGE = 'Slug is already in use';
export const SLUG_REQUIRED_MESSAGE =
  'A slug cannot be made from this title (it has no Latin letters or digits). ' +
  'Enter a slug using lowercase letters, digits and hyphens, e.g. "my-movie".';
export const SLUG_GENERATION_FAILED_MESSAGE =
  'Could not generate a unique slug for this title. Try again, or enter a slug.';

/**
 * True when `error` is Prisma's unique-constraint violation (P2002). Only ever call it on an
 * error thrown by a Movie write (create or update), never on a whole transaction's error.
 *
 * ASSUMPTION: every P2002 on Movie is a slug clash. Movie's only unique columns are `id`
 * (generated by the database, so it never clashes) and `slug`. The error cannot be narrowed
 * further: Prisma 7.10.1 with @prisma/adapter-pg sets no `meta.target`; the index name is only
 * in the undocumented `meta.driverAdapterError.cause.constraint.index`. If Movie gains another
 * unique field (or a compound unique / id), this must be updated to tell the constraints apart.
 * movie.admin.service.test.ts reads the Prisma schema and fails when that happens.
 */
export function isMovieSlugClash(error: unknown): boolean {
  return error instanceof Prisma.PrismaClientKnownRequestError && error.code === 'P2002';
}

/** Every column: admins see the whole movie. Listed explicitly, like the public select. */
export const adminMovieSelect = {
  id: true,
  slug: true,
  title: true,
  synopsis: true,
  durationMinutes: true,
  language: true,
  genres: true,
  rating: true,
  director: true,
  cast: true,
  releaseDate: true,
  trailerUrl: true,
  status: true,
  posterUrl: true,
  posterPublicId: true,
  bannerUrl: true,
  bannerPublicId: true,
  isActive: true,
  deletedAt: true,
  createdAt: true,
  updatedAt: true,
} as const satisfies Prisma.MovieSelect;

export type AdminMovieRow = Pick<Movie, keyof typeof adminMovieSelect>;

/** Field by field. Timestamps as ISO 8601, `releaseDate` as YYYY-MM-DD. */
export function toAdminMovie(row: AdminMovieRow): AdminMovie {
  return {
    id: row.id,
    slug: row.slug,
    title: row.title,
    synopsis: row.synopsis,
    durationMinutes: row.durationMinutes,
    language: row.language,
    genres: [...row.genres],
    rating: row.rating,
    director: row.director,
    cast: [...row.cast],
    releaseDate: row.releaseDate === null ? null : formatDateOnly(row.releaseDate),
    trailerUrl: row.trailerUrl,
    status: row.status,
    posterUrl: row.posterUrl,
    posterPublicId: row.posterPublicId,
    bannerUrl: row.bannerUrl,
    bannerPublicId: row.bannerPublicId,
    isActive: row.isActive,
    deletedAt: row.deletedAt === null ? null : row.deletedAt.toISOString(),
    createdAt: row.createdAt.toISOString(),
    updatedAt: row.updatedAt.toISOString(),
  };
}

/** A `YYYY-MM-DD` (already validated) as the UTC-midnight Date Prisma writes to a `@db.Date`. */
export function parseDateOnly(date: string): Date {
  return new Date(`${date}T00:00:00.000Z`);
}

/**
 * The `where` of the admin list: every given filter, combined with AND. `deleted` defaults to
 * 'exclude' in the query schema. The search matches title OR slug, case-insensitively, as a
 * literal substring (see escapeLikePattern: Prisma does not escape LIKE wildcards).
 */
export function adminMovieListWhere(query: AdminMovieListQuery): Prisma.MovieWhereInput {
  const where: Prisma.MovieWhereInput = {};
  if (query.status !== undefined) where.status = query.status;
  if (query.isActive !== undefined) where.isActive = query.isActive;
  if (query.deleted === 'exclude') where.deletedAt = null;
  else if (query.deleted === 'only') where.deletedAt = { not: null };
  if (query.search !== undefined) {
    const term = escapeLikePattern(query.search);
    where.OR = [
      { title: { contains: term, mode: 'insensitive' } },
      { slug: { contains: term, mode: 'insensitive' } },
    ];
  }
  return where;
}

type SortOrder = AdminMovieListQuery['order'];

/** One entry per ADMIN_MOVIE_SORT_FIELDS value (the Record type makes a missing one a type error). */
const ADMIN_LIST_SORT: Record<
  AdminMovieListQuery['sort'],
  (order: SortOrder) => Prisma.MovieOrderByWithRelationInput
> = {
  updatedAt: (order) => ({ updatedAt: order }),
  createdAt: (order) => ({ createdAt: order }),
  title: (order) => ({ title: order }),
  releaseDate: (order) => ({ releaseDate: { sort: order, nulls: 'last' } }),
};

/**
 * The `orderBy` of the admin list: the chosen column, then `id` in the same direction as a
 * unique tie-breaker, so pages never overlap or skip rows (and asc is exactly desc reversed).
 * `releaseDate` is the only nullable sort column: undated movies go last in both directions,
 * like the public list (Postgres would otherwise put NULLs first for desc).
 */
export function adminMovieListOrderBy({
  sort,
  order,
}: Pick<AdminMovieListQuery, 'sort' | 'order'>): Prisma.MovieOrderByWithRelationInput[] {
  return [ADMIN_LIST_SORT[sort](order), { id: order }];
}

/** A 409 on `body.slug`, so the admin form can show it next to the field. */
const slugConflict = (message: string) =>
  new AppError(409, ERROR_CODES.CONFLICT, message, [{ path: ['body', 'slug'], message }]);

/** Thrown inside a create transaction when the movie insert hit the slug's unique index. */
class SlugClash extends Error {
  constructor(readonly slug: string) {
    super(`Slug clash on ${slug}`);
    this.name = 'SlugClash';
  }
}

/** Who made an admin change, for the audit row. Raw request values; writeAudit fits them. */
export interface AuditActor {
  adminId: string;
  ipAddress?: string | undefined;
  userAgent?: string | undefined;
}

export type MovieAdminDb = Pick<PrismaClient, 'movie' | 'auditLog' | '$transaction'>;

export interface MovieAdminServiceDeps {
  db: MovieAdminDb;
  /** The app's one cache; public movie responses are dropped from it after each committed write. */
  cache: Pick<MemoryCache, 'invalidatePrefix'>;
}

/** Admin movie reads and writes. Every write is audited in the same transaction. */
export function createMovieAdminService({ db, cache }: MovieAdminServiceDeps) {
  /**
   * One transaction: insert the movie with `slug`, then its CREATE audit row. A unique
   * violation from the insert becomes a SlugClash (and the transaction rolls back); any other
   * error, including an audit failure, rolls the insert back and propagates unchanged.
   */
  function insertWithAudit(
    input: MovieCreateBody,
    slug: string,
    actor: AuditActor,
  ): Promise<AdminMovieRow> {
    return db.$transaction(async (tx) => {
      let row: AdminMovieRow;
      try {
        row = await tx.movie.create({
          data: {
            slug,
            title: input.title,
            synopsis: input.synopsis ?? null,
            durationMinutes: input.durationMinutes,
            language: input.language ?? null,
            genres: input.genres,
            rating: input.rating ?? null,
            director: input.director ?? null,
            cast: input.cast,
            releaseDate:
              input.releaseDate === undefined || input.releaseDate === null
                ? null
                : parseDateOnly(input.releaseDate),
            trailerUrl: input.trailerUrl ?? null,
            status: input.status,
          },
          select: adminMovieSelect,
        });
      } catch (error) {
        // Slug-clash detection. Assumes Movie's only unique columns are `id` (generated) and
        // `slug`, and adapter-pg's P2002 has no `meta.target`, so ANY P2002 from this insert is
        // the slug. Update isMovieSlugClash if Movie gains another unique field (its guard test
        // in movie.admin.service.test.ts fails when that happens).
        if (isMovieSlugClash(error)) throw new SlugClash(slug);
        throw error;
      }
      await writeAudit(tx, {
        action: 'CREATE',
        adminId: actor.adminId,
        entity: AUDIT_ENTITY,
        entityId: row.id,
        details: { title: row.title, slug: row.slug },
        ipAddress: actor.ipAddress,
        userAgent: actor.userAgent,
      });
      return row;
    });
  }

  /** The admin chose the slug: it is used as given or refused with a 409, never changed. */
  async function createWithExplicitSlug(
    input: MovieCreateBody,
    slug: string,
    actor: AuditActor,
  ): Promise<AdminMovieRow> {
    // Soft-deleted movies keep their slug: slugs are never reused.
    const taken = await db.movie.findUnique({ where: { slug }, select: { id: true } });
    if (taken) throw slugConflict(SLUG_IN_USE_MESSAGE);
    try {
      return await insertWithAudit(input, slug, actor);
    } catch (error) {
      // Taken by a concurrent request between the check and the insert.
      if (error instanceof SlugClash) throw slugConflict(SLUG_IN_USE_MESSAGE);
      throw error;
    }
  }

  /**
   * The slug comes from the title: `base`, else `base-2`, `base-3`, ... (the first one no movie
   * has, deleted ones included). A concurrent insert can still take it before ours commits; then
   * the whole transaction is retried with the next free suffix, up to AUTO_SLUG_MAX_ATTEMPTS.
   */
  async function createWithGeneratedSlug(
    input: MovieCreateBody,
    actor: AuditActor,
  ): Promise<AdminMovieRow> {
    const base = slugify(input.title);
    if (base === '') {
      // No fallback slug by design (e.g. a Sinhala- or Tamil-only title): ask the admin.
      throw new AppError(400, ERROR_CODES.VALIDATION_ERROR, SLUG_REQUIRED_MESSAGE, [
        { path: ['body', 'slug'], message: SLUG_REQUIRED_MESSAGE },
      ]);
    }

    // Slugs that clashed in an earlier attempt, in case the clashing row is not visible yet.
    const clashed: string[] = [];
    for (let attempt = 1; attempt <= AUTO_SLUG_MAX_ATTEMPTS; attempt += 1) {
      const rows = await db.movie.findMany({
        where: { slug: { startsWith: base } },
        select: { slug: true },
      });
      const slug = firstFreeSlug(base, [...rows.map((r) => r.slug), ...clashed]);
      try {
        return await insertWithAudit(input, slug, actor);
      } catch (error) {
        if (!(error instanceof SlugClash)) throw error;
        clashed.push(error.slug);
      }
    }
    throw slugConflict(SLUG_GENERATION_FAILED_MESSAGE);
  }

  return {
    /**
     * Creates a movie and its CREATE audit row atomically, then drops the cached public movie
     * responses. Throws 400 VALIDATION_ERROR when no slug was given and none can be made from
     * the title, and 409 CONFLICT when the slug is (or stays) taken.
     */
    async create(input: MovieCreateBody, actor: AuditActor): Promise<AdminMovie> {
      const row =
        input.slug === undefined
          ? await createWithGeneratedSlug(input, actor)
          : await createWithExplicitSlug(input, input.slug, actor);
      // Only after the commit, so no request can re-cache the pre-insert list.
      invalidatePublicMovies(cache);
      return toAdminMovie(row);
    },

    /**
     * One page of movies for the admin table, filtered, searched and sorted (see
     * adminMovieListWhere / adminMovieListOrderBy). Never cached: admins must see their own
     * writes at once. A page past the end has no items but still the full `total`.
     *
     * The page and the count are two independent queries run in parallel, not a transaction:
     * at Postgres's default READ COMMITTED level each statement takes its own snapshot anyway,
     * so a transaction would add BEGIN/COMMIT round trips and hold a pooled connection without
     * making the two consistent. A write landing between them can make `total` differ from the
     * rows by one, which the next fetch corrects; that is fine for an admin table.
     */
    async list(query: AdminMovieListQuery): Promise<AdminMovieListResponse> {
      const where = adminMovieListWhere(query);
      const [rows, total] = await Promise.all([
        db.movie.findMany({
          where,
          orderBy: adminMovieListOrderBy(query),
          skip: (query.page - 1) * query.pageSize,
          take: query.pageSize,
          select: adminMovieSelect,
        }),
        db.movie.count({ where }),
      ]);
      return { items: rows.map(toAdminMovie), page: query.page, pageSize: query.pageSize, total };
    },

    /** Any movie by id, soft-deleted or hidden ones included. 404 when there is none. */
    async getById(id: string): Promise<AdminMovie> {
      const row = await db.movie.findUnique({ where: { id }, select: adminMovieSelect });
      if (!row) throw notFound('Movie not found');
      return toAdminMovie(row);
    },
  };
}

export type MovieAdminService = ReturnType<typeof createMovieAdminService>;
