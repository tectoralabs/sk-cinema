/**
 * True when `error` is Prisma's unique-constraint violation (P2002). Only ever call it on an
 * error thrown by a Movie write (create or update), never on a whole transaction's error.
 *
 * ASSUMPTION: every P2002 on Movie is a slug clash. Movie's only unique columns are `id`
 * (generated by the database, so it never clashes) and `slug`. The error cannot be narrowed
 * further: Prisma 7.10.1 with @prisma/adapter-pg sets no `meta.target`; the index name is only
 * in the undocumented `meta.driverAdapterError.cause.constraint.index`. If Movie gains another
 * unique field (or a compound unique / id), this must be updated to tell the constraints apart.
 * movie.admin.service.test.ts reads the Prisma schema and fails when that happens.
 */
export function isMovieSlugClash(error: unknown): boolean {
  return error instanceof Prisma.PrismaClientKnownRequestError && error.code === 'P2002';
}

