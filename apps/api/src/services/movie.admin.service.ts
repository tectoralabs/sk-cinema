/** A `YYYY-MM-DD` (already validated) as the UTC-midnight Date Prisma writes to a `@db.Date`. */
export function parseDateOnly(date: string): Date {
  return new Date(`${date}T00:00:00.000Z`);
}

/** A field PATCH /api/admin/movies/:id may change. */
export type MovieEditableField = keyof MovieUpdateBody;

/**
 * Every field of movieUpdateBodySchema, in a fixed order (the Record type makes a missing one a
 * type error, and indexing AdminMovie with them proves each is a movie column).
 */
const EDITABLE_FIELDS = Object.keys({
  title: true,
  slug: true,
  synopsis: true,
  durationMinutes: true,
  language: true,
  genres: true,
  rating: true,
  director: true,
  cast: true,
  releaseDate: true,
  trailerUrl: true,
} satisfies Record<MovieEditableField, true>) as MovieEditableField[];

/** An editable field's value in API form (releaseDate as YYYY-MM-DD). JSON-safe for the audit. */
type EditableValue = AdminMovie[MovieEditableField];

/** A Record, not an interface, so it is assignable to Prisma's JSON input types. */
export type FieldChange = Record<'from' | 'to', EditableValue>;

/** Only the fields that actually change; empty when the update is a no-op. */
export type MovieDetailChanges = Partial<Record<MovieEditableField, FieldChange>>;

/** Lists are equal element by element (order and case matter); everything else by `===`. */
function sameEditableValue(a: EditableValue, b: EditableValue): boolean {
  if (Array.isArray(a) || Array.isArray(b)) {
    return (
      Array.isArray(a) &&
      Array.isArray(b) &&
      a.length === b.length &&
      a.every((value, i) => value === b[i])
    );
  }
  return a === b;
}

/**
 * Compares a validated update body with the stored movie, both in API form, so dates compare as
 * YYYY-MM-DD and `null` (cleared) equals a stored NULL. Fields the body omits are ignored.
 */
export function movieDetailChanges(current: AdminMovie, body: MovieUpdateBody): MovieDetailChanges {
  const changes: MovieDetailChanges = {};
  for (const field of EDITABLE_FIELDS) {
    const to = body[field];
    if (to === undefined) continue;
    const from = current[field];
    if (!sameEditableValue(from, to)) changes[field] = { from, to };
  }
  return changes;
}

/** The Prisma `data` writing exactly the changed fields (releaseDate back to a DATE). */
function detailUpdateData(changes: MovieDetailChanges): Prisma.MovieUpdateInput {
  const data: Record<string, EditableValue | Date> = {};
  for (const field of EDITABLE_FIELDS) {
    const change = changes[field];
    if (change === undefined) continue;
    data[field] =
      field === 'releaseDate' && typeof change.to === 'string'
        ? parseDateOnly(change.to)
        : change.to;
  }
  // Keys are EDITABLE_FIELDS (movie columns, see above); values come from the validated body.
  return data;
}

/**
 * The `where` of the admin list: every given filter, combined with AND. `deleted` defaults to
 * 'exclude' in the query schema. The search matches title OR slug, case-insensitively, as a
 * literal substring (see escapeLikePattern: Prisma does not escape LIKE wildcards).
 */
export function adminMovieListWhere(query: AdminMovieListQuery): Prisma.MovieWhereInput {
  const where: Prisma.MovieWhereInput = {};
  if (query.status !== undefined) where.status = query.status;
  if (query.isActive !== undefined) where.isActive = query.isActive;
  if (query.deleted === 'exclude') where.deletedAt = null;
  else if (query.deleted === 'only') where.deletedAt = { not: null };
  if (query.search !== undefined) {
    const term = escapeLikePattern(query.search);
    where.OR = [
      { title: { contains: term, mode: 'insensitive' } },
      { slug: { contains: term, mode: 'insensitive' } },
    ];
  }
  return where;
}

type SortOrder = AdminMovieListQuery['order'];

/** One entry per ADMIN_MOVIE_SORT_FIELDS value (the Record type makes a missing one a type error). */
const ADMIN_LIST_SORT: Record<
  AdminMovieListQuery['sort'],
  (order: SortOrder) => Prisma.MovieOrderByWithRelationInput
> = {
  updatedAt: (order) => ({ updatedAt: order }),
  createdAt: (order) => ({ createdAt: order }),
  title: (order) => ({ title: order }),
  releaseDate: (order) => ({ releaseDate: { sort: order, nulls: 'last' } }),
};

/**
 * The `orderBy` of the admin list: the chosen column, then `id` in the same direction as a
 * unique tie-breaker, so pages never overlap or skip rows (and asc is exactly desc reversed).
 * `releaseDate` is the only nullable sort column: undated movies go last in both directions,
 * like the public list (Postgres would otherwise put NULLs first for desc).
 */
export function adminMovieListOrderBy({
  sort,
  order,
}: Pick<AdminMovieListQuery, 'sort' | 'order'>): Prisma.MovieOrderByWithRelationInput[] {
  return [ADMIN_LIST_SORT[sort](order), { id: order }];
}

/** A 409 on `body.slug`, so the admin form can show it next to the field. */
const slugConflict = (message: string) =>
  new AppError(409, ERROR_CODES.CONFLICT, message, [{ path: ['body', 'slug'], message }]);

/** Thrown inside a create or update transaction when the movie write hit the slug's unique index. */
class SlugClash extends Error {
  constructor(readonly slug: string) {
    super(`Slug clash on ${slug}`);
    this.name = 'SlugClash';
  }
}

/**
 * Thrown inside a write transaction when the conditional update or delete matched no row
 * (P2025): a concurrent request deleted, soft-deleted or restored the movie after it was read.
 * Turned into a 404 or 409 after the rollback (see lostWriteError), never a 500.
 */
class MovieGone extends Error {
  constructor() {
    super('Movie changed before the write');
    this.name = 'MovieGone';
  }
}

const isRecordNotFound = (error: unknown) =>
  error instanceof Prisma.PrismaClientKnownRequestError && error.code === 'P2025';

/** A 409 for a write to a soft-deleted movie: it exists, so the admin can restore it first. */
const restoreFirst = () => new AppError(409, ERROR_CODES.CONFLICT, MOVIE_RESTORE_FIRST_MESSAGE);

/** What one admin write changes: the Prisma data and the audit row describing it. */
interface PlannedChange {
  data: Prisma.MovieUpdateInput;
  audit: Required<Pick<AuditEntry, 'action' | 'details'>>;
}

/** Where a movie is: live (deletedAt null) or in the trash (soft-deleted). */
type MoviePlace = 'live' | 'trash';

/**
 * Why a movie cannot be moved from `from`: 404 when there is no such movie, 409 with
 * `conflictMessage` when it is somewhere else. Null when it can be moved.
 */
function misplacedMovieError(
  row: Pick<Movie, 'deletedAt'> | null,
  from: MoviePlace,
  conflictMessage: string,
): AppError | null {
  if (row === null) return notFound(MOVIE_NOT_FOUND_MESSAGE);
  const place: MoviePlace = row.deletedAt === null ? 'live' : 'trash';
  return place === from ? null : new AppError(409, ERROR_CODES.CONFLICT, conflictMessage);
}

/** The columns every soft delete, restore and hard delete audit row records. */
type AuditedMovieRow = Pick<Movie, 'id' | 'title' | 'slug'>;

/** One soft delete, restore or hard delete (see moveMovie). */
interface MovieMove<R extends AuditedMovieRow> {
  /** Where the movie must be for the move; anywhere else is a 409 with `conflictMessage`. */
  from: MoviePlace;
  conflictMessage: string;
  /** The conditional write. `where` is `{ id, deletedAt }` repeating the `from` check. */
  write: (tx: Prisma.TransactionClient, where: Prisma.MovieWhereUniqueInput) => Promise<R>;
  /** The audit row, from the row the write returned. */
  audit: (row: R) => Required<Pick<AuditEntry, 'action' | 'details'>>;
}

/** Re-exported for existing importers; defined with writeAudit, which all admin services use. */
export type { AuditActor };

export type MovieAdminDb = Pick<PrismaClient, 'movie' | 'auditLog' | '$transaction'>;

export interface MovieAdminServiceDeps {
  db: MovieAdminDb;
  /** The app's one cache; public movie responses are dropped from it after each committed write. */
  cache: Pick<MemoryCache, 'invalidatePrefix'>;
}

/**
 * Admin movie reads and writes. Every write that changes something is audited in the same
 * transaction; a write that would change nothing is not made, audited or cache-invalidating.
 */
export function createMovieAdminService({ db, cache }: MovieAdminServiceDeps) {
  /**
   * The answer to a conditional write that matched no row (MovieGone), from the movie re-read
   * after the rollback (the transaction is over, so this read is a new statement):
   * - 404 when it is gone;
   * - 409 `conflictMessage` when it is somewhere other than `from`, as if that change had come
   *   before the request;
   * - 409 MOVIE_CHANGED_MESSAGE when it is back at `from` (it left and returned between our read
   *   and our write). The write is not retried: the request was based on a state that changed.
   * Never a 500 (unless the re-read itself fails).
   */
  async function lostWriteError(
    id: string,
    from: MoviePlace,
    conflictMessage: string,
  ): Promise<AppError> {
    const now = await db.movie.findUnique({ where: { id }, select: { deletedAt: true } });
    return (
      misplacedMovieError(now, from, conflictMessage) ??
      new AppError(409, ERROR_CODES.CONFLICT, MOVIE_CHANGED_MESSAGE)
    );
  }

  /**
   * One transaction: insert the movie with `slug`, then its CREATE audit row. A unique
   * violation from the insert becomes a SlugClash (and the transaction rolls back); any other
   * error, including an audit failure, rolls the insert back and propagates unchanged.
   */
  function insertWithAudit(
    input: MovieCreateBody,
    slug: string,
    actor: AuditActor,
  ): Promise<AdminMovieRow> {
    return db.$transaction(async (tx) => {
      let row: AdminMovieRow;
      try {
        row = await tx.movie.create({
          data: {
            slug,
            title: input.title,
            synopsis: input.synopsis ?? null,
            durationMinutes: input.durationMinutes,
            language: input.language ?? null,
            genres: input.genres,
            rating: input.rating ?? null,
            director: input.director ?? null,
            cast: input.cast,
            releaseDate:
              input.releaseDate === undefined || input.releaseDate === null
                ? null
                : parseDateOnly(input.releaseDate),
            trailerUrl: input.trailerUrl ?? null,
            status: input.status,
          },
          select: adminMovieSelect,
        });
      } catch (error) {
        // Slug-clash detection. Assumes Movie's only unique columns are `id` (generated) and
        // `slug`, and adapter-pg's P2002 has no `meta.target`, so ANY P2002 from this insert is
        // the slug. Update isMovieSlugClash if Movie gains another unique field (its guard test
        // in movie.admin.service.test.ts fails when that happens).
        if (isMovieSlugClash(error)) throw new SlugClash(slug);
        throw error;
      }
      await writeAudit(tx, {
        action: 'CREATE',
        adminId: actor.adminId,
        entity: AUDIT_ENTITY,
        entityId: row.id,
        details: { title: row.title, slug: row.slug },
        ipAddress: actor.ipAddress,
        userAgent: actor.userAgent,
      });
      return row;
    });
  }

  /** The admin chose the slug: it is used as given or refused with a 409, never changed. */
  async function createWithExplicitSlug(
    input: MovieCreateBody,
    slug: string,
    actor: AuditActor,
  ): Promise<AdminMovieRow> {
    // Soft-deleted movies keep their slug: slugs are never reused.
    const taken = await db.movie.findUnique({ where: { slug }, select: { id: true } });
    if (taken) throw slugConflict(SLUG_IN_USE_MESSAGE);
    try {
      return await insertWithAudit(input, slug, actor);
    } catch (error) {
      // Taken by a concurrent request between the check and the insert.
      if (error instanceof SlugClash) throw slugConflict(SLUG_IN_USE_MESSAGE);
      throw error;
    }
  }

  /**
   * The slug comes from the title: `base`, else `base-2`, `base-3`, ... (the first one no movie
   * has, deleted ones included). A concurrent insert can still take it before ours commits; then
   * the whole transaction is retried with the next free suffix, up to AUTO_SLUG_MAX_ATTEMPTS.
   */
  async function createWithGeneratedSlug(
    input: MovieCreateBody,
    actor: AuditActor,
  ): Promise<AdminMovieRow> {
    const base = slugify(input.title);
    if (base === '') {
      // No fallback slug by design (e.g. a Sinhala- or Tamil-only title): ask the admin.
      throw new AppError(400, ERROR_CODES.VALIDATION_ERROR, SLUG_REQUIRED_MESSAGE, [
        { path: ['body', 'slug'], message: SLUG_REQUIRED_MESSAGE },
      ]);
    }

    // Slugs that clashed in an earlier attempt, in case the clashing row is not visible yet.
    const clashed: string[] = [];
    for (let attempt = 1; attempt <= AUTO_SLUG_MAX_ATTEMPTS; attempt += 1) {
      // Only `base` and `base-...` rows, not every slug starting with the letters of `base`
      // (`theatre` for `the`). `startsWith` is not LIKE-escaped by Prisma, which is safe here:
      // a slugify() base only contains [a-z0-9-], never the wildcards `%` or `_`.
      const rows = await db.movie.findMany({
        where: { OR: [{ slug: base }, { slug: { startsWith: `${base}-` } }] },
        select: { slug: true },
      });
      const taken = rows.map((r) => r.slug).filter((slug) => isSlugOrSuffixed(slug, base));
      const slug = firstFreeSlug(base, [...taken, ...clashed]);
      try {
        return await insertWithAudit(input, slug, actor);
      } catch (error) {
        if (!(error instanceof SlugClash)) throw error;
        clashed.push(error.slug);
      }
    }
    throw slugConflict(SLUG_GENERATION_FAILED_MESSAGE);
  }

  /**
   * The shared flow of every movie update, in one transaction:
   * 1. read the movie (404 unknown, 409 soft-deleted, whatever the body);
   * 2. `plan` compares the body with it; null means nothing would change, so the current movie
   *    is returned with no write, no audit row and no cache invalidation;
   * 3. a new slug is pre-checked against every movie, soft-deleted ones included (409);
   * 4. the conditional update `where: { id, deletedAt: null }`;
   * 5. the audit row (its failure rolls the update back and propagates as a 500);
   * then, only after the commit, the public movie cache is dropped.
   *
   * A P2025 from step 4 means a concurrent request removed or soft-deleted the movie after
   * step 1. It never becomes a 500: lostWriteError re-reads the movie after the rollback and
   * answers 404, 409 MOVIE_RESTORE_FIRST_MESSAGE, or 409 MOVIE_CHANGED_MESSAGE when the movie
   * is live again (soft-deleted and restored in between). Any other error is a 500.
   *
   * Concurrency: the from-values come from step 1. Two admins changing the same field at the
   * same moment can both be recorded as changes from the same value; the row ends up with the
   * last committed write, as Postgres serialises the two UPDATEs on the row lock.
   */
  async function applyChange(
    id: string,
    actor: AuditActor,
    plan: (current: AdminMovieRow) => PlannedChange | null,
  ): Promise<AdminMovie> {
    let outcome: { row: AdminMovieRow; changed: boolean };
    try {
      outcome = await db.$transaction(async (tx) => {
        const current = await tx.movie.findUnique({ where: { id }, select: adminMovieSelect });
        if (current === null) throw notFound(MOVIE_NOT_FOUND_MESSAGE);
        if (current.deletedAt !== null) throw restoreFirst();

        const change = plan(current);
        if (change === null) return { row: current, changed: false };

        const newSlug = typeof change.data.slug === 'string' ? change.data.slug : undefined;
        if (newSlug !== undefined) {
          // Only reached when the slug really changes, so any holder is another movie.
          // Soft-deleted movies keep their slug: slugs are never reused.
          const holder = await tx.movie.findUnique({
            where: { slug: newSlug },
            select: { id: true },
          });
          if (holder) throw slugConflict(SLUG_IN_USE_MESSAGE);
        }

        let row: AdminMovieRow;
        try {
          row = await tx.movie.update({
            where: { id, deletedAt: null },
            data: change.data,
            select: adminMovieSelect,
          });
        } catch (error) {
          // Slug-clash detection, as in insertWithAudit: ANY P2002 from this update is taken to
          // be the slug (Movie's only unique columns are the generated `id` and `slug`, and
          // adapter-pg's P2002 has no `meta.target`). Postgres only checks a unique index for a
          // value the update writes, so in practice only a slug change can hit it: a concurrent
          // request took the slug after the pre-check. Update isMovieSlugClash if Movie gains
          // another unique field (its guard test in movie.admin.service.test.ts fails then).
          if (isMovieSlugClash(error)) throw new SlugClash(newSlug ?? current.slug);
          if (isRecordNotFound(error)) throw new MovieGone();
          throw error;
        }

        await writeAudit(tx, {
          ...change.audit,
          adminId: actor.adminId,
          entity: AUDIT_ENTITY,
          entityId: row.id,
          ipAddress: actor.ipAddress,
          userAgent: actor.userAgent,
        });
        return { row, changed: true };
      });
    } catch (error) {
      if (error instanceof SlugClash) throw slugConflict(SLUG_IN_USE_MESSAGE);
      // Deleted, soft-deleted (or soft-deleted and restored) between the read and the update.
      if (error instanceof MovieGone) {
        throw await lostWriteError(id, 'live', MOVIE_RESTORE_FIRST_MESSAGE);
      }
      throw error;
    }

    // Only after the commit, so no request can re-cache the pre-update movie.
    if (outcome.changed) invalidatePublicMovies(cache);
    return toAdminMovie(outcome.row);
  }

  /**
   * The shared flow of soft delete, restore and hard delete, in one transaction:
   * 1. read the movie: 404 when unknown, 409 when it is not at `move.from`;
   * 2. the conditional write, `where: { id, deletedAt }` repeating that check;
   * 3. the audit row, from the row the write returned (its failure rolls the write back and
   *    propagates as a 500);
   * then, only after the commit, the public movie cache is dropped. There is no no-op: a move
   * always changes the movie, or is refused.
   *
   * A P2025 from step 2 means a concurrent request moved or removed the movie after step 1 (at
   * READ COMMITTED, Postgres re-checks the WHERE on the locked row). It never becomes a 500:
   * lostWriteError re-reads the movie after the rollback and answers as if that change had come
   * first (404, or 409 `move.conflictMessage`), or 409 MOVIE_CHANGED_MESSAGE when the movie is
   * back at `move.from` (moved away and back in between). Any other error is a 500.
   */
  async function moveMovie<R extends AuditedMovieRow>(
    id: string,
    actor: AuditActor,
    move: MovieMove<R>,
  ): Promise<R> {
    const where: Prisma.MovieWhereUniqueInput = {
      id,
      deletedAt: move.from === 'live' ? null : { not: null },
    };
    let row: R;
    try {
      row = await db.$transaction(async (tx) => {
        const current = await tx.movie.findUnique({ where: { id }, select: { deletedAt: true } });
        const refused = misplacedMovieError(current, move.from, move.conflictMessage);
        if (refused) throw refused;

        let written: R;
        try {
          written = await move.write(tx, where);
        } catch (error) {
          if (isRecordNotFound(error)) throw new MovieGone();
          throw error;
        }

        await writeAudit(tx, {
          ...move.audit(written),
          adminId: actor.adminId,
          entity: AUDIT_ENTITY,
          entityId: written.id,
          ipAddress: actor.ipAddress,
          userAgent: actor.userAgent,
        });
        return written;
      });
    } catch (error) {
      if (error instanceof MovieGone) {
        throw await lostWriteError(id, move.from, move.conflictMessage);
      }
      throw error;
    }

    // Only after the commit, so no request can re-cache the movie as it was.
    invalidatePublicMovies(cache);
    return row;
  }

  return {
    /**
     * Creates a movie and its CREATE audit row atomically, then drops the cached public movie
     * responses. Throws 400 VALIDATION_ERROR when no slug was given and none can be made from
     * the title, and 409 CONFLICT when the slug is (or stays) taken.
     */
    async create(input: MovieCreateBody, actor: AuditActor): Promise<AdminMovie> {
      const row =
        input.slug === undefined
          ? await createWithGeneratedSlug(input, actor)
          : await createWithExplicitSlug(input, input.slug, actor);
      // Only after the commit, so no request can re-cache the pre-insert list.
      invalidatePublicMovies(cache);
      return toAdminMovie(row);
    },

    /**
     * One page of movies for the admin table, filtered, searched and sorted (see
     * adminMovieListWhere / adminMovieListOrderBy). Never cached: admins must see their own
     * writes at once. A page past the end has no items but still the full `total`.
     *
     * The page and the count are two independent queries run in parallel, not a transaction:
     * at Postgres's default READ COMMITTED level each statement takes its own snapshot anyway,
     * so a transaction would add BEGIN/COMMIT round trips and hold a pooled connection without
     * making the two consistent. A write landing between them can make `total` differ from the
     * rows by one, which the next fetch corrects; that is fine for an admin table.
     */
    async list(query: AdminMovieListQuery): Promise<AdminMovieListResponse> {
      const where = adminMovieListWhere(query);
      const [rows, total] = await Promise.all([
        db.movie.findMany({
          where,
          orderBy: adminMovieListOrderBy(query),
          skip: (query.page - 1) * query.pageSize,
          take: query.pageSize,
          select: adminMovieSelect,
        }),
        db.movie.count({ where }),
      ]);
      return { items: rows.map(toAdminMovie), page: query.page, pageSize: query.pageSize, total };
    },

    /** Any movie by id, soft-deleted or hidden ones included. 404 when there is none. */
    async getById(id: string): Promise<AdminMovie> {
      const row = await db.movie.findUnique({ where: { id }, select: adminMovieSelect });
      if (!row) throw notFound(MOVIE_NOT_FOUND_MESSAGE);
      return toAdminMovie(row);
    },

    /**
     * Changes the given detail fields (see applyChange). Only the fields whose value differs are
     * written and audited (UPDATE, `{ changes: { field: { from, to } } }`). The slug changes only
     * when the body has one: never because the title changed. 409 when a new slug is taken.
     */
    update(id: string, body: MovieUpdateBody, actor: AuditActor): Promise<AdminMovie> {
      return applyChange(id, actor, (current) => {
        const changes = movieDetailChanges(toAdminMovie(current), body);
        if (Object.keys(changes).length === 0) return null;
        return {
          data: detailUpdateData(changes),
          audit: { action: 'UPDATE', details: { changes } },
        };
      });
    },

    /** Moves the movie to `status` (STATUS_CHANGE, `{ field: 'status', from, to }`). */
    setStatus(id: string, status: MovieStatus, actor: AuditActor): Promise<AdminMovie> {
      return applyChange(id, actor, (current) =>
        current.status === status
          ? null
          : {
              data: { status },
              audit: {
                action: 'STATUS_CHANGE',
                details: { field: 'status', from: current.status, to: status },
              },
            },
      );
    },

    /** Shows or hides the movie (STATUS_CHANGE, `{ field: 'isActive', from, to }`). */
    setActive(id: string, isActive: boolean, actor: AuditActor): Promise<AdminMovie> {
      return applyChange(id, actor, (current) =>
        current.isActive === isActive
          ? null
          : {
              data: { isActive },
              audit: {
                action: 'STATUS_CHANGE',
                details: { field: 'isActive', from: current.isActive, to: isActive },
              },
            },
      );
    },

    /**
     * Moves a live movie to the trash: sets `deletedAt` (DELETE, `{ mode: 'soft', title, slug }`).
     * It disappears from the public site but keeps its slug, isActive and status, so a restore
     * brings it back as it was. 409 when it is already in the trash.
     */
    async softDelete(id: string, actor: AuditActor): Promise<AdminMovie> {
      const row = await moveMovie(id, actor, {
        from: 'live',
        conflictMessage: MOVIE_ALREADY_DELETED_MESSAGE,
        write: (tx, where) =>
          tx.movie.update({ where, data: { deletedAt: new Date() }, select: adminMovieSelect }),
        audit: ({ title, slug }) => ({ action: 'DELETE', details: { mode: 'soft', title, slug } }),
      });
      return toAdminMovie(row);
    },

    /**
     * Takes a movie out of the trash: clears `deletedAt`
     * (UPDATE, `{ restored: true, title, slug }`). isActive and status are untouched. Its slug
     * cannot have been taken meanwhile, as slugs are unique across every movie, deleted ones
     * included. 409 when it is not in the trash.
     */
    async restore(id: string, actor: AuditActor): Promise<AdminMovie> {
      const row = await moveMovie(id, actor, {
        from: 'trash',
        conflictMessage: MOVIE_NOT_DELETED_MESSAGE,
        write: (tx, where) =>
          tx.movie.update({ where, data: { deletedAt: null }, select: adminMovieSelect }),
        audit: ({ title, slug }) => ({
          action: 'UPDATE',
          details: { restored: true, title, slug },
        }),
      });
      return toAdminMovie(row);
    },

    /**
     * Removes a movie from the trash for good (DELETE, `{ mode: 'hard', title, slug }`); its slug
     * becomes free. Only a movie already in the trash: 409 for a live one. The caller must
     * restrict this to SUPER_ADMIN (the route does). The audit row survives the movie:
     * AuditLog.entityId is a plain column, with no foreign key to Movie.
     */
    async hardDelete(id: string, actor: AuditActor): Promise<void> {
      await moveMovie(id, actor, {
        from: 'trash',
        conflictMessage: MOVIE_DELETE_FIRST_MESSAGE,
        // The movie's showtimes go with it: Showtime.movieId is ON DELETE CASCADE in Postgres.
        // Phase 6: delete its Cloudinary images (posterPublicId, bannerPublicId) once this commits.
        write: (tx, where) =>
          tx.movie.delete({ where, select: { id: true, title: true, slug: true } }),
        audit: ({ title, slug }) => ({ action: 'DELETE', details: { mode: 'hard', title, slug } }),
      });
    },
  };
}

export type MovieAdminService = ReturnType<typeof createMovieAdminService>;
