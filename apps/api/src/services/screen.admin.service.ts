export const SCREEN_NOT_FOUND_MESSAGE = 'Screen not found';
/** A soft-deleted screen cannot be edited or shown/hidden until it is restored. */
export const SCREEN_RESTORE_FIRST_MESSAGE = 'Restore the screen first';
/** DELETE /:id on a screen that is already soft-deleted. */
export const SCREEN_ALREADY_DELETED_MESSAGE = 'Screen is already deleted';
/** POST /:id/restore on a screen that is not soft-deleted. */
export const SCREEN_NOT_DELETED_MESSAGE = 'Screen is not deleted';
/** See MOVIE_CHANGED_MESSAGE: the screen left and came back between our read and our write. */
export const SCREEN_CHANGED_MESSAGE =
  'The screen was changed by someone else. Reload and try again.';
/** Create or rename to a name a live screen has (ignoring case). */
export const SCREEN_NAME_IN_USE_MESSAGE = 'A screen with this name already exists';
/** Create or rename to a name only a soft-deleted screen has (ignoring case). */
export const SCREEN_NAME_DELETED_MESSAGE =
  'A deleted screen has this name. Restore that screen instead, or choose another name.';
/** Restore of a screen whose name another live screen has (ignoring case). */
export const SCREEN_RESTORE_NAME_IN_USE_MESSAGE =
  'Another screen has this name. Rename that screen before restoring this one.';
export const SCREEN_DEACTIVATE_HAS_SHOWTIMES_MESSAGE =
  'This screen has upcoming showtimes. Delete them or move them to another screen before hiding it.';
export const SCREEN_DELETE_HAS_SHOWTIMES_MESSAGE =
  'This screen has upcoming showtimes. Delete them or move them to another screen before deleting it.';

/**
 * True when `error` is Prisma's unique-constraint violation (P2002). Only ever call it on an
 * error thrown by a Screen write (create or update), never on a whole transaction's error.
 *
 * ASSUMPTION: every P2002 on Screen is a name clash (`Screen_name_key`). Screen's only unique
 * columns are `id` (generated by the database, so it never clashes) and `name`. As for Movie,
 * Prisma 7.10.1 with @prisma/adapter-pg sets no `meta.target` (the index name is only in the
 * undocumented `meta.driverAdapterError.cause.constraint.index`), so the error is not narrowed
 * further. If Screen gains another unique field (or a compound unique / id), this must be
 * updated; screen.admin.service.test.ts reads the Prisma schema and fails when that happens.
 */
export function isScreenNameClash(error: unknown): boolean {
  return error instanceof Prisma.PrismaClientKnownRequestError && error.code === 'P2002';
}

/** Every column: admins see the whole screen. */
export const adminScreenSelect = {
  id: true,
  name: true,
  capacity: true,
  isActive: true,
  deletedAt: true,
  createdAt: true,
  updatedAt: true,
} as const satisfies Prisma.ScreenSelect;

export type AdminScreenRow = Pick<Screen, keyof typeof adminScreenSelect>;

/** Field by field, timestamps as ISO 8601. */
export function toAdminScreen(row: AdminScreenRow): AdminScreen {
  return {
    id: row.id,
    name: row.name,
    capacity: row.capacity,
    isActive: row.isActive,
    deletedAt: row.deletedAt === null ? null : row.deletedAt.toISOString(),
    createdAt: row.createdAt.toISOString(),
    updatedAt: row.updatedAt.toISOString(),
  };
}

/** A field PATCH /api/admin/screens/:id may change. */
export type ScreenEditableField = keyof ScreenUpdateBody;

/** Every field of screenUpdateBodySchema (the Record type makes a missing one a type error). */
const EDITABLE_FIELDS = Object.keys({
  name: true,
  capacity: true,
} satisfies Record<ScreenEditableField, true>) as ScreenEditableField[];

type EditableValue = AdminScreen[ScreenEditableField];

/** A Record, not an interface, so it is assignable to Prisma's JSON input types. */
export type ScreenFieldChange = Record<'from' | 'to', EditableValue>;

/** Only the fields that actually change; empty when the update is a no-op. */
export type ScreenDetailChanges = Partial<Record<ScreenEditableField, ScreenFieldChange>>;

/**
 * Compares a validated update body with the stored screen. Names compare exactly, so a change
 * of case is a change; `capacity: null` equals a stored NULL. Omitted fields are ignored.
 */
export function screenDetailChanges(
  current: AdminScreen,
  body: ScreenUpdateBody,
): ScreenDetailChanges {
  const changes: ScreenDetailChanges = {};
  for (const field of EDITABLE_FIELDS) {
    const to = body[field];
    if (to === undefined) continue;
    const from = current[field];
    if (from !== to) changes[field] = { from, to };
  }
  return changes;
}

/**
 * The `where` finding screens whose name equals `name` ignoring case, other than `excludeId`.
 *
 * Prisma 7.10.1 sends `equals` with `mode: 'insensitive'` as `"name" ILIKE $1` WITHOUT escaping
 * the value, so `%`, `_` and `\` in a name would be wildcards ("A_C" would match "ABC");
 * escapeLikePattern makes them literal. ILIKE lower-cases both sides character by character
 * (C.UTF-8), so accents still count: "Écran" and "ecran" differ.
 */
export function screenNameMatchWhere(name: string, excludeId?: string): Prisma.ScreenWhereInput {
  const where: Prisma.ScreenWhereInput = {
    name: { equals: escapeLikePattern(name), mode: 'insensitive' },
  };
  if (excludeId !== undefined) where.id = { not: excludeId };
  return where;
}

/**
 * The `where` of the admin list: every given filter, combined with AND. `deleted` defaults to
 * 'exclude' in the query schema. The search matches the name case-insensitively, as a literal
 * substring (see escapeLikePattern).
 */
export function adminScreenListWhere(query: AdminScreenListQuery): Prisma.ScreenWhereInput {
  const where: Prisma.ScreenWhereInput = {};
  if (query.isActive !== undefined) where.isActive = query.isActive;
  if (query.deleted === 'exclude') where.deletedAt = null;
  else if (query.deleted === 'only') where.deletedAt = { not: null };
  if (query.search !== undefined) {
    where.name = { contains: escapeLikePattern(query.search), mode: 'insensitive' };
  }
  return where;
}

/**
 * The `orderBy` of the admin list: by name in the database collation (C.UTF-8 on Neon: by code
 * point, so "Screen 10" sorts before "Screen 2" and upper case before lower case), then `id` as
 * a unique tie-breaker so pages never overlap or skip rows.
 */
export const ADMIN_SCREEN_LIST_ORDER_BY = [
  { name: 'asc' },
  { id: 'asc' },
] as const satisfies Prisma.ScreenOrderByWithRelationInput[];

/** A 409 on `body.name`, so the admin form can show it next to the field. */
const nameConflict = (message: string) =>
  new AppError(409, ERROR_CODES.CONFLICT, message, [{ path: ['body', 'name'], message }]);

/** Thrown inside a create or update transaction when the screen write hit `Screen_name_key`. */
class NameClash extends Error {
  constructor() {
    super('Screen name clash');
    this.name = 'NameClash';
  }
}

/**
 * Thrown inside a write transaction when the conditional update matched no row (P2025): the
 * screen was removed, soft-deleted or restored after it was read. Turned into a 404 or 409
 * after the rollback (see lostWriteError), never a 500.
 */
class ScreenGone extends Error {
  constructor() {
    super('Screen changed before the write');
    this.name = 'ScreenGone';
  }
}

/** Where a screen is: live (deletedAt null) or soft-deleted. */
type ScreenPlace = 'live' | 'trash';

/**
 * Why a screen cannot be written from `from`: 404 when there is no such screen, 409 with
 * `conflictMessage` when it is somewhere else. Null when it can.
 */
function misplacedScreenError(
  row: Pick<Screen, 'deletedAt'> | null,
  from: ScreenPlace,
  conflictMessage: string,
): AppError | null {
  if (row === null) return notFound(SCREEN_NOT_FOUND_MESSAGE);
  const place: ScreenPlace = row.deletedAt === null ? 'live' : 'trash';
  return place === from ? null : new AppError(409, ERROR_CODES.CONFLICT, conflictMessage);
}

/** What one admin write changes: the Prisma data and the audit row describing it. */
interface PlannedChange {
  data: Prisma.ScreenUpdateInput;
  audit: Required<Pick<AuditEntry, 'action' | 'details'>>;
}

/** One screen write (see writeScreen). */
interface ScreenWrite {
  /** Where the screen must be; anywhere else is a 409 with `conflictMessage`. */
  from: ScreenPlace;
  conflictMessage: string;
  /**
   * Runs under the screen's row lock with the current row: checks (and throws) whatever the
   * write depends on, then returns the change, or null when nothing would change.
   */
  plan: (tx: Prisma.TransactionClient, current: AdminScreenRow) => Promise<PlannedChange | null>;
}

export type ScreenAdminDb = Pick<PrismaClient, 'screen' | 'showtime' | 'auditLog' | '$transaction'>;

export interface ScreenAdminServiceDeps {
  db: ScreenAdminDb;
  /**
   * The app's one cache. Public showtime responses include the screen name and are cached
   * under the public movies prefix, so they are dropped after each committed screen write.
   */
  cache: Pick<MemoryCache, 'invalidatePrefix'>;
  /** Injectable clock for tests ("upcoming" showtimes, deletedAt). Defaults to the current time. */
  now?: () => Date;
}

/**
 * Admin screen reads and writes. Every write that changes something is audited in the same
 * transaction; a write that would change nothing is not made, audited or cache-invalidating.
 *
 * Names are unique ignoring case, across every screen (soft-deleted ones included, as the
 * database's own unique index on `name` is). The check is in the app, not the database:
 * KNOWN RACE: two concurrent creates (or renames) whose names differ only in case, e.g.
 * "Screen 3" and "screen 3", can both pass the check before either commits, and the
 * case-sensitive `Screen_name_key` index lets both in. Exactly equal names are still caught by
 * that index (P2002, mapped to the same 409). Closing the gap needs a unique index on
 * `lower(name)` (a schema change, proposed for Phase 10); admins create screens rarely, so the
 * window is small and the outcome (two screens named alike) is visible and fixable by a rename.
 */
export function createScreenAdminService({
  db,
  cache,
  now = () => new Date(),
}: ScreenAdminServiceDeps) {
  /**
   * 409 when another screen has `name` ignoring case (other than `excludeId`): the "restore
   * it" hint when every match is soft-deleted, the plain "in use" message otherwise.
   */
  async function assertNameFree(
    tx: Prisma.TransactionClient,
    name: string,
    excludeId?: string,
  ): Promise<void> {
    const matches = await tx.screen.findMany({
      where: screenNameMatchWhere(name, excludeId),
      select: { deletedAt: true },
    });
    if (matches.length === 0) return;
    throw nameConflict(
      matches.some((match) => match.deletedAt === null)
        ? SCREEN_NAME_IN_USE_MESSAGE
        : SCREEN_NAME_DELETED_MESSAGE,
    );
  }

  /**
   * The answer to a conditional write that matched no row (ScreenGone), from the screen re-read
   * after the rollback: 404 when it is gone, 409 `conflictMessage` when it is somewhere other
   * than `from`, 409 SCREEN_CHANGED_MESSAGE when it is back at `from`. Never a 500 (unless the
   * re-read itself fails).
   */
  async function lostWriteError(
    id: string,
    from: ScreenPlace,
    conflictMessage: string,
  ): Promise<AppError> {
    const row = await db.screen.findUnique({ where: { id }, select: { deletedAt: true } });
    return (
      misplacedScreenError(row, from, conflictMessage) ??
      new AppError(409, ERROR_CODES.CONFLICT, SCREEN_CHANGED_MESSAGE)
    );
  }

  /**
   * The shared flow of every write to an existing screen, in one transaction:
   * 1. lock the Screen row (lib/locks.ts) BEFORE reading anything, so the reads below see every
   *    earlier writer's commit and showtime writers on this screen wait for us;
   * 2. read the screen: 404 unknown, 409 `conflictMessage` when it is not at `from`;
   * 3. `plan` checks what the write depends on (name, upcoming showtimes) and returns the
   *    change; null means nothing would change, so the screen is returned with no write, no
   *    audit row and no cache invalidation;
   * 4. the conditional update `where: { id, deletedAt }` repeating the `from` check;
   * 5. the audit row (its failure rolls the update back and propagates as a 500);
   * then, only after the commit, the public cache is dropped.
   *
   * With the row lock held, step 4 cannot miss on real Postgres; a P2025 is still answered by
   * lostWriteError (404 / 409), never a 500. A P2002 from step 4 is a name taken by a
   * concurrent write after step 3 (409 SCREEN_NAME_IN_USE_MESSAGE).
   */
  async function writeScreen(
    id: string,
    actor: AuditActor,
    write: ScreenWrite,
  ): Promise<AdminScreen> {
    const where: Prisma.ScreenWhereUniqueInput = {
      id,
      deletedAt: write.from === 'live' ? null : { not: null },
    };
    let outcome: { row: AdminScreenRow; changed: boolean };
    try {
      outcome = await db.$transaction(async (tx) => {
        if (!(await lockScreen(tx, id))) throw notFound(SCREEN_NOT_FOUND_MESSAGE);
        const current = await tx.screen.findUnique({ where: { id }, select: adminScreenSelect });
        if (current === null) throw notFound(SCREEN_NOT_FOUND_MESSAGE);
        const refused = misplacedScreenError(current, write.from, write.conflictMessage);
        if (refused) throw refused;

        const change = await write.plan(tx, current);
        if (change === null) return { row: current, changed: false };

        let row: AdminScreenRow;
        try {
          row = await tx.screen.update({ where, data: change.data, select: adminScreenSelect });
        } catch (error) {
          // Name-clash detection: ANY P2002 from this update is the name (see isScreenNameClash).
          if (isScreenNameClash(error)) throw new NameClash();
          if (isRecordNotFound(error)) throw new ScreenGone();
          throw error;
        }

        await writeAudit(tx, {
          ...change.audit,
          adminId: actor.adminId,
          entity: AUDIT_ENTITY,
          entityId: row.id,
          ipAddress: actor.ipAddress,
          userAgent: actor.userAgent,
        });
        return { row, changed: true };
      });
    } catch (error) {
      if (error instanceof NameClash) throw nameConflict(SCREEN_NAME_IN_USE_MESSAGE);
      if (error instanceof ScreenGone) {
        throw await lostWriteError(id, write.from, write.conflictMessage);
      }
      throw error;
    }

    // Only after the commit, so no request can re-cache the screen as it was.
    if (outcome.changed) invalidatePublicMovies(cache);
    return toAdminScreen(outcome.row);
  }

  return {
    /**
     * Creates an active screen and its CREATE audit row (`{ name, capacity }`) atomically, then
     * drops the cached public responses. 409 CONFLICT on `body.name` when the name is taken
     * ignoring case (by a soft-deleted screen: the message suggests restoring it).
     */
    async create(input: ScreenCreateBody, actor: AuditActor): Promise<AdminScreen> {
      let row: AdminScreenRow;
      try {
        row = await db.$transaction(async (tx) => {
          await assertNameFree(tx, input.name);
          let created: AdminScreenRow;
          try {
            created = await tx.screen.create({
              data: { name: input.name, capacity: input.capacity ?? null },
              select: adminScreenSelect,
            });
          } catch (error) {
            // Same assumption as isScreenNameClash: any P2002 from this insert is the name,
            // taken by a concurrent create after the check above.
            if (isScreenNameClash(error)) throw new NameClash();
            throw error;
          }
          await writeAudit(tx, {
            action: 'CREATE',
            adminId: actor.adminId,
            entity: AUDIT_ENTITY,
            entityId: created.id,
            details: { name: created.name, capacity: created.capacity },
            ipAddress: actor.ipAddress,
            userAgent: actor.userAgent,
          });
          return created;
        });
      } catch (error) {
        if (error instanceof NameClash) throw nameConflict(SCREEN_NAME_IN_USE_MESSAGE);
        throw error;
      }
      // Only after the commit.
      invalidatePublicMovies(cache);
      return toAdminScreen(row);
    },

    /**
     * One page of screens for the admin table (see adminScreenListWhere and
     * ADMIN_SCREEN_LIST_ORDER_BY). Never cached. Page and count run in parallel, not in a
     * transaction, for the reasons given in the movie admin list.
     */
    async list(query: AdminScreenListQuery): Promise<AdminScreenListResponse> {
      const where = adminScreenListWhere(query);
      const [rows, total] = await Promise.all([
        db.screen.findMany({
          where,
          orderBy: [...ADMIN_SCREEN_LIST_ORDER_BY],
          skip: (query.page - 1) * query.pageSize,
          take: query.pageSize,
          select: adminScreenSelect,
        }),
        db.screen.count({ where }),
      ]);
      return { items: rows.map(toAdminScreen), page: query.page, pageSize: query.pageSize, total };
    },

    /** Any screen by id, soft-deleted or hidden ones included. 404 when there is none. */
    async getById(id: string): Promise<AdminScreen> {
      const row = await db.screen.findUnique({ where: { id }, select: adminScreenSelect });
      if (!row) throw notFound(SCREEN_NOT_FOUND_MESSAGE);
      return toAdminScreen(row);
    },

    /**
     * Changes the name and/or capacity (UPDATE, `{ changes: { field: { from, to } } }`, only
     * the fields that differ). A new name is checked against every other screen ignoring case
     * (409 on `body.name`); the screen's own name in another case is allowed.
     */
    update(id: string, body: ScreenUpdateBody, actor: AuditActor): Promise<AdminScreen> {
      return writeScreen(id, actor, {
        from: 'live',
        conflictMessage: SCREEN_RESTORE_FIRST_MESSAGE,
        plan: async (tx, current) => {
          const changes = screenDetailChanges(toAdminScreen(current), body);
          if (changes.name === undefined && changes.capacity === undefined) return null;
          const data: Prisma.ScreenUpdateInput = {};
          if (changes.name !== undefined && body.name !== undefined) {
            // Excluding itself: renaming "Screen 1" to "screen 1" is allowed.
            await assertNameFree(tx, body.name, current.id);
            data.name = body.name;
          }
          if (changes.capacity !== undefined && body.capacity !== undefined) {
            data.capacity = body.capacity;
          }
          return { data, audit: { action: 'UPDATE', details: { changes } } };
        },
      });
    },

    /**
     * Shows or hides the screen (STATUS_CHANGE, `{ field: 'isActive', from, to }`). Hiding is
     * refused (409, `{ futureShowtimeCount }`) while the screen has upcoming showtimes.
     */
    setActive(id: string, isActive: boolean, actor: AuditActor): Promise<AdminScreen> {
      return writeScreen(id, actor, {
        from: 'live',
        conflictMessage: SCREEN_RESTORE_FIRST_MESSAGE,
        plan: async (tx, current) => {
          if (current.isActive === isActive) return null;
          if (!isActive) {
            await refuseIfFutureShowtimes(
              tx,
              { screenId: id },
              now(),
              SCREEN_DEACTIVATE_HAS_SHOWTIMES_MESSAGE,
            );
          }
          return {
            data: { isActive },
            audit: {
              action: 'STATUS_CHANGE',
              details: { field: 'isActive', from: current.isActive, to: isActive },
            },
          };
        },
      });
    },

    /**
     * Soft-deletes a live screen: sets `deletedAt` (DELETE, `{ mode: 'soft', name }`). Refused
     * (409, `{ futureShowtimeCount }`) while it has upcoming showtimes, and with 409 when it is
     * already deleted. There is no hard delete: Showtime.screenId is ON DELETE RESTRICT and
     * past showtimes keep pointing at the screen.
     */
    softDelete(id: string, actor: AuditActor): Promise<AdminScreen> {
      return writeScreen(id, actor, {
        from: 'live',
        conflictMessage: SCREEN_ALREADY_DELETED_MESSAGE,
        plan: async (tx, current) => {
          await refuseIfFutureShowtimes(
            tx,
            { screenId: id },
            now(),
            SCREEN_DELETE_HAS_SHOWTIMES_MESSAGE,
          );
          return {
            data: { deletedAt: now() },
            audit: { action: 'DELETE', details: { mode: 'soft', name: current.name } },
          };
        },
      });
    },

    /**
     * Restores a soft-deleted screen: clears `deletedAt` (UPDATE, `{ restored: true, name }`);
     * isActive is untouched. 409 when it is not deleted, and when a LIVE screen has its name
     * ignoring case. Other soft-deleted screens with that name do not block: otherwise two
     * deleted screens named alike would block each other forever (neither can be renamed
     * until restored).
     */
    restore(id: string, actor: AuditActor): Promise<AdminScreen> {
      return writeScreen(id, actor, {
        from: 'trash',
        conflictMessage: SCREEN_NOT_DELETED_MESSAGE,
        plan: async (tx, current) => {
          const holder = await tx.screen.findFirst({
            where: { ...screenNameMatchWhere(current.name, current.id), deletedAt: null },
            select: { id: true },
          });
          if (holder) {
            throw new AppError(409, ERROR_CODES.CONFLICT, SCREEN_RESTORE_NAME_IN_USE_MESSAGE);
          }
          return {
            data: { deletedAt: null },
            audit: { action: 'UPDATE', details: { restored: true, name: current.name } },
          };
        },
      });
    },
  };
}

export type ScreenAdminService = ReturnType<typeof createScreenAdminService>;
